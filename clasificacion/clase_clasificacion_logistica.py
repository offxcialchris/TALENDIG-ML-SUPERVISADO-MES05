import pandas as pd
from sklearn.linear_model import LogisticRegression
from sklearn.metrics import accuracy_score

X_train = pd.read_csv("X_train.csv")
X_test = pd.read_csv("X_test.csv")
y_train = pd.read_csv("y_train.csv").squeeze()
y_test = pd.read_csv("y_test.csv").squeeze()

print("X_train:, ", X_train.shape)
print("X_test:, ", X_test.shape)
print("y_train:, ", y_train.shape)
print("y_test:, ", y_test.shape)
print()
print("Columnas de X_train")
print(list(X_train.columns))


# Modelo
modelo = LogisticRegression(max_iter=1000)
modelo.fit(X_train, y_train)

print("Modelo entrenado con: ", X_train.shape[0], "pasajeros de entrenamiento")

#Predicciones y probabilidades
y_pred = modelo.predict(X_test)
y_proba = modelo.predict_proba(X_test)

print("Predicciones (primeras 5):", y_pred[:5])
print()
print("Probabilidades (segunda 5): - [Sobrevivio o no sobrevivio]")
print(y_proba[:5].round(3))
print()
print("Valores reales (primeras 5):", y_test.values[:5])

# Metrica - Acurracy
accuracy = accuracy_score(y_test, y_pred)
print(f"Accuracy: {accuracy:.4f} ({accuracy * 100:.1f}% de predicciones correctas)") # el ".1f" es un especificador de formato


























































































































































































































































































































































































































